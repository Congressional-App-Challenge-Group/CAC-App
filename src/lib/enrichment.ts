import type { Decision, DecisionDraft, DraftField, DraftedFields } from "@/types";
import { orgNames } from "@/lib/civic";
import { extractAddressFromText, extractZipFromText, parsePetitionNumber } from "@/lib/geography";

/**
 * Plain-language generation.
 *
 * The hard rule from the product's own principles: never publish a sentence the
 * official record does not support. Everything here is therefore a *draft*, and
 * `generateDrafts` prefers a model but always falls back to a deterministic
 * template that can only recombine wording actually present in the record.
 *
 * Nothing generated by this module reaches a public page until an editor sets
 * the draft's status to "approved".
 */

export const PROMPT_VERSION = "civiclens-plain-language-v1";

export const draftFieldLabels: Record<DraftField, string> = {
  summary: "Plain-language summary",
  whyItMatters: "Why it matters",
  nextStep: "Next step",
  beforeText: "Before",
  afterText: "After",
};

export type GeneratedDraft = {
  decisionId: string;
  field: DraftField;
  draftText: string;
  model: string;
  promptVersion: string;
  sourceExcerpts: string[];
};

/* -------------------------------------------------------------------------- */
/* Source excerpts — the only material a draft is allowed to draw from         */
/* -------------------------------------------------------------------------- */

export function cleanRecordText(value: string): string {
  return value
    .replace(/<[^>]*>/g, " ")
    .replace(/&nbsp;|&#160;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();
}

function excerpt(value: string, max: number): string {
  const text = cleanRecordText(value);
  if (text.length <= max) return text;
  return `${text.slice(0, max).replace(/\s+\S*$/, "")}…`;
}

/** True when a record's body adds nothing beyond its title. */
export function isTitleDuplicate(body: string, title: string): boolean {
  const a = cleanRecordText(body).toLowerCase();
  const b = cleanRecordText(title).toLowerCase();
  return !a || a === b || a.startsWith(b) || b.startsWith(a);
}

export function buildSourceExcerpts(decision: Decision): string[] {
  const excerpts: string[] = [`Title: ${decision.title}`];
  if (!isTitleDuplicate(decision.summary, decision.title)) {
    excerpts.push(`Record text: ${excerpt(decision.summary, 900)}`);
  }
  if (decision.latestUpdate) excerpts.push(`Latest official update: ${excerpt(decision.latestUpdate, 400)}`);
  if (decision.nextStep) excerpts.push(`Confirmed next step: ${excerpt(decision.nextStep, 300)}`);
  for (const event of decision.timeline.slice(-4)) {
    excerpts.push(
      `Timeline ${event.date} (${event.stage}): ${excerpt(event.title, 200)}${
        event.whatChanged ? ` — ${excerpt(event.whatChanged, 200)}` : ""
      }`,
    );
  }
  for (const source of decision.sources.slice(0, 4)) {
    excerpts.push(`Official source: ${source.organization} — ${source.title} (${source.url})`);
  }
  return excerpts;
}

/* -------------------------------------------------------------------------- */
/* Deterministic drafting                                                      */
/* -------------------------------------------------------------------------- */

function applicantFromTitle(title: string): string | null {
  const match = title.match(/\bby\s+(.+?)\s*$/i);
  if (!match) return null;
  const applicant = match[1].replace(/[.;,]+$/, "").trim();
  if (applicant.length < 3 || applicant.length > 90) return null;
  return applicant;
}

/** Zoning transitions are only reported when the record literally states them. */
export function zoningTransition(text: string): { from: string; to: string } | null {
  const match = cleanRecordText(text).match(
    /\bfrom\s+([A-Z][A-Z0-9-]{0,8})\s+to\s+([A-Z][A-Z0-9-]{0,8})\b/,
  );
  if (!match) return null;
  return { from: match[1], to: match[2] };
}

