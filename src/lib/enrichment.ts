const SYSTEM_PROMPT = [
  "You write plain-language summaries of local government records for residents.",
  "You may ONLY use facts contained in the supplied official record excerpts.",
  "Never invent or infer an address, dollar amount, date, deadline, affected group, or outcome.",
  "If a field cannot be written from the excerpts, omit that key entirely.",
  "Prefer short, concrete sentences. No jargon, no marketing language.",
  'Reply with JSON only, shaped {"summary"?:string,"whyItMatters"?:string,"nextStep"?:string,"beforeText"?:string,"afterText"?:string}.',
].join(" ");

function parseJsonObject(content: string): Record<string, unknown> | null {
  const cleaned = content.trim().replace(/^```(?:json)?/i, "").replace(/```$/, "").trim();
  try {
    const parsed = JSON.parse(cleaned);
    return parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}

async function callModelProvider(
  decision: Decision,
  excerpts: string[],
): Promise<Partial<Record<DraftField, string>> | null> {
  const apiKey = process.env.ENRICHMENT_API_KEY;
  if (!apiKey) return null;
  const baseUrl = (process.env.ENRICHMENT_BASE_URL || "https://api.openai.com/v1").replace(/\/+$/, "");
  const model = process.env.ENRICHMENT_MODEL || "gpt-4o-mini";

  try {
    const response = await fetch(`${baseUrl}/chat/completions`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${apiKey}` },
      body: JSON.stringify({
        model,
        temperature: 0.2,
        response_format: { type: "json_object" },
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          {
            role: "user",
            content: [
              `Local government: ${orgNames[decision.organization]}`,
              `Topic: ${decision.topic}`,
              `Current stage: ${decision.status}`,
              "",
              "Official record excerpts:",
              ...excerpts.map((line) => `- ${line}`),
            ].join("\n"),
          },
        ],
      }),
    });

    if (!response.ok) return null;
    const payload = (await response.json()) as {
      choices?: Array<{ message?: { content?: string } }>;
    };
    const content = payload.choices?.[0]?.message?.content;
    if (!content) return null;
    const parsed = parseJsonObject(content);
    if (!parsed) return null;

    const fields: DraftField[] = ["summary", "whyItMatters", "nextStep", "beforeText", "afterText"];
    const result: Partial<Record<DraftField, string>> = {};
    for (const field of fields) {
      const value = parsed[field];
      if (typeof value === "string" && value.trim().length > 20) result[field] = value.trim();
    }
    return Object.keys(result).length ? result : null;
  } catch {
    // Any provider problem quietly falls back to the deterministic drafts, which
    // are always safe to show to an editor.
    return null;
  }
}

/**
 * Produce drafts for one decision. Uses the model when configured, and always
 * falls back to the deterministic templates.
 */
export async function generateDrafts(
  decision: Decision,
  options: { useModel?: boolean } = {},
): Promise<GeneratedDraft[]> {
  const excerpts = buildSourceExcerpts(decision);
  const useModel = options.useModel ?? Boolean(process.env.ENRICHMENT_API_KEY);

  if (useModel) {
    const modeled = await callModelProvider(decision, excerpts);
    if (modeled && modeled.summary) {
      const model = process.env.ENRICHMENT_MODEL || "gpt-4o-mini";
      return (Object.entries(modeled) as Array<[DraftField, string]>).map(([field, draftText]) => ({
        decisionId: decision.id,
        field,
        draftText,
        model,
        promptVersion: PROMPT_VERSION,
        sourceExcerpts: excerpts,
      }));
    }
  }

  return draftDecisionPlainLanguage(decision);
}

